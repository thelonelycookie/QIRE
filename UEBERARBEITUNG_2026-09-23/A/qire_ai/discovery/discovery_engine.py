from __future__ import annotations
import json
from pathlib import Path
from typing import Any, Dict, List

from qire_ai.config import LOGS_DIR, REPORTS_DIR
from qire_ai.research_store import ResearchStore
from .experiment_idea_generator import generate_experiment_ideas
from .hypothesis_generator import generate_hypotheses
from .result_analyzer import summarize_results, diagnose_qire
from .discovery_report import write_discovery_report
from .proposal_schema import ResearchProposal, validate_proposal, proposal_to_jobs
from .reproduction_planner import plan_reproduction
from .pareto_gap_finder import non_dominated


def run_discovery(limit: int = 120) -> Dict[str, Any]:
    store = ResearchStore()
    rows = store.load_raw_results(include_failed=True)
    summary = summarize_results(rows)
    hypotheses = generate_hypotheses(rows)
    proposals = generate_experiment_ideas(rows, limit=limit)
    validated = []
    blocked = []
    for p in proposals:
        ok, reason = validate_proposal(p)
        record = p.as_dict(); record["validation_ok"] = ok; record["validation_reason"] = reason
        if ok: validated.append(record)
        else: blocked.append(record)
    payload = {
        "summary": summary,
        "hypotheses": hypotheses,
        "diagnostics": diagnose_qire(rows),
        "pareto_front_count": len(non_dominated(rows)),
        "proposals": validated,
        "blocked_proposals": blocked,
    }
    LOGS_DIR.mkdir(parents=True, exist_ok=True); REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    with (LOGS_DIR / "discovery_proposals.jsonl").open("w", encoding="utf-8") as f:
        for p in validated:
            f.write(json.dumps(p, ensure_ascii=False, sort_keys=True) + "\n")
    with (LOGS_DIR / "discovery_blocked.jsonl").open("w", encoding="utf-8") as f:
        for p in blocked:
            f.write(json.dumps(p, ensure_ascii=False, sort_keys=True) + "\n")
    report = write_discovery_report(payload)
    payload["report"] = str(report)
    _write_negative_and_pareto_reports(payload)
    # Also refresh reproduction plan.
    payload["reproduction_plan"] = plan_reproduction(rows)
    (REPORTS_DIR / "next_experiment_plan.md").write_text(_next_experiment_plan_md(validated), encoding="utf-8")
    return payload


def _next_experiment_plan_md(proposals: List[Dict[str, Any]]) -> str:
    lines = ["# Next Experiment Plan", "", "These experiments are generated by Discovery. They are proposals, not evidence.", ""]
    for p in proposals[:15]:
        lines.append(f"## {p.get('proposal_id')}")
        lines.append(p.get("hypothesis", ""))
        lines.append(f"- Datasets: {', '.join(p.get('datasets', []))}")
        lines.append(f"- Baselines: {', '.join(p.get('baseline', []))}")
        lines.append(f"- Success: {p.get('success_criterion')}")
        lines.append("")
    return "\n".join(lines)


def load_validated_proposals(path: Path | None = None) -> List[ResearchProposal]:
    path = path or (LOGS_DIR / "discovery_proposals.jsonl")
    if not path.exists():
        run_discovery()
    proposals = []
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip(): continue
            data = json.loads(line)
            for k in ["validation_ok", "validation_reason"]:
                data.pop(k, None)
            try:
                proposals.append(ResearchProposal(**data))
            except Exception:
                continue
    return proposals


def discovery_jobs(seeds: List[int] | None = None, epochs: int = 80, max_jobs: int = 200):
    jobs = []
    for p in load_validated_proposals():
        try:
            jobs.extend(proposal_to_jobs(p, seeds=seeds or [1,2,3], epochs=epochs))
        except Exception:
            continue
        if len(jobs) >= max_jobs:
            break
    return jobs[:max_jobs]


def _write_negative_and_pareto_reports(payload: Dict[str, Any]) -> None:
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    neg = REPORTS_DIR / "negative_results.md"
    lines = ["# Negative Result Mining", "", "Failures and dominated results are treated as research information, not deleted.", ""]
    for d in payload.get("diagnostics", []):
        lines.append(f"- {d.get('type')}: {d.get('message')} ({d.get('dataset','')}, {d.get('method','')})")
    if len(lines) <= 4:
        lines.append("- No negative-result patterns detected yet. Run baseline/ablation first.")
    neg.write_text("\n".join(lines), encoding="utf-8")
    pareto = REPORTS_DIR / "pareto_gaps.md"
    lines = ["# Pareto Gap Analysis", "", f"Non-dominated row count: {payload.get('pareto_front_count', 0)}", "", "Discovery proposals with type `pareto_gap_candidate` target observed gaps between accuracy and resource cost."]
    for p in payload.get("proposals", []):
        if p.get("type") == "pareto_gap_candidate":
            lines.append(f"- {p.get('proposal_id')}: {p.get('hypothesis')}")
    pareto.write_text("\n".join(lines), encoding="utf-8")
